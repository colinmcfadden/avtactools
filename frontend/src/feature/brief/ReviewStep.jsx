import React, { useState } from "react";
import Icon from "../ui/Icon";

/*
 * Setup, step 3: review (the design's "Brief setup 3"). The pages as the brief compiles them now, one shown with its
 * constants, facts, items and script, what could not be briefed, and the PDF's options. The PDF itself and its figures
 * are made on the server (docs/MISSION_BRIEF.md §2.6, §2.7) from this same model: what is shown here is what it prints.
 */

const OPTIONS = [
  { key: "script", label: "Script under each figure", text: "Who briefs it, and what to say" },
  { key: "constants", label: "Mission constants on every page", text: "The band across the top" },
  { key: "lzCards", label: "LZ/PZ cards", text: "Appendix, one for each LZ/PZ in the flow" },
  { key: "navLogs", label: "Nav logs", text: "Appendix, one for each route" },
  { key: "iimc", label: "IIMC card", text: "Appendix, when the IIMC procedure is set" },
  { key: "writeIns", label: "Write-in lines for blanks", text: "Off leaves blank fields out" },
];
const MAPS = [["satellite", "Satellite"], ["topo", "Topo"], ["sectional", "Sectional"]];
const PAPERS = [["letter", "Letter"], ["a4", "A4"]];

const pageTitle = (page, steps) => {
  if (page.kind === "cover" || page.kind === "step") {
    const step = steps.find((s) => s.id === page.stepId);
    return step ? `${step.number} ${step.title}` : "";
  }
  return page.title;
};

const Sentence = ({ parts }) => (
  <p>
    {parts.map((part, j) => (part.writeIn !== undefined
      // eslint-disable-next-line react/no-array-index-key
      ? <span key={j} className="brief-writein">{part.label ? `${part.label} ` : ""}________</span>
      // eslint-disable-next-line react/no-array-index-key
      : <React.Fragment key={j}>{part.text}</React.Fragment>))}
  </p>
);

const ReviewStep = ({ model, doc, setDoc, coverTitle }) => {
  const [pageN, setPageN] = useState(1);
  const page = model.pages.find((p) => p.n === pageN) ?? model.pages[0];
  const step = page && (page.kind === "cover" || page.kind === "step") ? model.steps.find((s) => s.id === page.stepId) : null;
  const options = model.options;
  const setOption = (key, value) => setDoc((d) => ({ ...d, options: { ...(d.options || {}), [key]: value } }));
  const figureMap = doc.options?.figureMap ?? "satellite";
  const paper = doc.options?.paper ?? "letter";

  return (
    <div className="brief-review">
      <nav className="brief-review__pages" aria-label="Pages">
        {model.pages.map((p) => (
          <button key={p.n} type="button" className="brief-review__page" aria-current={p.n === page?.n ? "true" : undefined} onClick={() => setPageN(p.n)}>
            <span className="brief-review__n" aria-label={`Page ${p.n}:`}>p{p.n}</span>
            <span>{pageTitle(p, model.steps)}</span>
          </button>
        ))}
      </nav>

      <article className="brief-sheet" aria-label={`Page ${page?.n ?? ""}`}>
        <div className="brief-sheet__mark">UNCLASSIFIED</div>
        {page?.kind === "cover" && (
          <header className="brief-sheet__cover">
            <div className="brief-sheet__format">{model.template.title.toUpperCase()}</div>
            <h3>{coverTitle ?? model.mission.name}</h3>
            <p>{model.mission.date ?? ""}</p>
          </header>
        )}
        {options.constants && model.constants.length > 0 && (
          <dl className="brief-sheet__constants">
            {model.constants.map((c) => (
              <div key={c.id}><dt>{c.short}</dt><dd>{c.value ?? "____"}</dd></div>
            ))}
          </dl>
        )}
        {step ? (
          <>
            <h4 className="brief-sheet__title">{step.number} {step.title} <span>· {step.who}</span></h4>
            {step.figure && <div className="brief-sheet__figure">Figure: {step.figure.kind}{step.figure.ref ? ` · ${step.figure.ref}` : ""}</div>}
            {step.facts.length > 0 && (
              <dl className="brief-sheet__facts">
                {step.facts.map((f) => <div key={f.key}><dt>{f.label}</dt><dd>{f.value ?? "____"}</dd></div>)}
              </dl>
            )}
            <ul className="brief-sheet__items">
              {step.items.filter((i) => i.kind !== "info").map((i) => (
                <li key={i.key}><span>{i.id}</span> {i.label}: {i.writeIn ? (options.writeIns ? <span className="brief-writein">________</span> : "") : i.text}</li>
              ))}
            </ul>
            {options.script && (
              <div className="brief-sheet__script">
                <div className="ui-label">Script · {step.who}</div>
                {step.script.map((parts, i) => <Sentence key={i} parts={parts} />)}
              </div>
            )}
          </>
        ) : (
          <p className="brief-hint">{page?.title}: drawn from the plan in the PDF.</p>
        )}
        <div className="brief-sheet__foot">Generated by EZ/PZ from the plan. Not an official form. · {page?.n} of {model.pages.length} · UNCLASSIFIED</div>
      </article>

      <aside className="brief-review__side">
        {model.problems.length > 0 && (
          <section className="brief-card brief-card--warn" aria-label="Not briefed">
            <h3 className="brief-h3"><Icon name="alertTriangle" size={14} /> Check before briefing</h3>
            <ul className="brief-problems">{model.problems.map((p) => <li key={`${p.ref}-${p.message}`}>{p.message}</li>)}</ul>
          </section>
        )}
        <section className="brief-card" aria-label="In the PDF">
          <h3 className="brief-h3">In the PDF</h3>
          {OPTIONS.map((o) => (
            <label key={o.key} className="brief-switch">
              <span><span>{o.label}</span><span className="brief-hint">{o.text}</span></span>
              <input type="checkbox" role="switch" checked={Boolean(options[o.key])} onChange={(e) => setOption(o.key, e.target.checked)} />
            </label>
          ))}
        </section>
        <section className="brief-card" aria-label="Figures and paper">
          <h3 className="brief-h3">Map in the figures</h3>
          <div role="radiogroup" aria-label="Map in the figures" className="brief-seg">
            {MAPS.map(([id, label]) => (
              <button key={id} type="button" role="radio" aria-checked={figureMap === id} className="brief-seg__opt" onClick={() => setOption("figureMap", id)}>{label}</button>
            ))}
          </div>
          <h3 className="brief-h3">Paper</h3>
          <div role="radiogroup" aria-label="Paper" className="brief-seg">
            {PAPERS.map(([id, label]) => (
              <button key={id} type="button" role="radio" aria-checked={paper === id} className="brief-seg__opt" onClick={() => setOption("paper", id)}>{label}</button>
            ))}
          </div>
          <p className="brief-hint">Every page is marked UNCLASSIFIED. EZ/PZ is for unclassified planning only: no CUI.</p>
        </section>
      </aside>
    </div>
  );
};

export default ReviewStep;
