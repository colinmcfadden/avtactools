"""Design tokens: one JSON file, a generated Kotlin object per client.

`contracts/tokens/tokens.json` is the source. Each client has the same names, so
"primary" or "touchTarget" means the same on the web, Android and iOS. This
script writes the Android file (Tokens.kt) and the iOS one (Tokens.swift).

    python contracts/scripts/tokens.py write   # regenerate both
    python contracts/scripts/tokens.py check   # fail if either generated file is stale

Standard library only.
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "contracts" / "tokens" / "tokens.json"
ANDROID = ROOT / "android" / "core-designsystem" / "src" / "main" / "kotlin" / "app" / "ezpztac" / "designsystem" / "Tokens.kt"

IOS = ROOT / "ios" / "Packages" / "EZPZCore" / "Sources" / "DesignTokens" / "Tokens.swift"

HEX = re.compile(r"^#[0-9A-Fa-f]{6}$")


def load():
    tokens = json.loads(SOURCE.read_text())
    palettes = tokens["colors"]
    names = set(palettes["dark"])
    for theme, palette in palettes.items():
        if set(palette) != names:
            raise SystemExit(f"{theme} palette has different colour names from dark: {sorted(set(palette) ^ names)}")
        for name, value in palette.items():
            if not HEX.match(value):
                raise SystemExit(f"{theme}.{name} is not #RRGGBB: {value!r}")
    return tokens


def upper_first(word):
    return word[0].upper() + word[1:]


def kotlin(tokens):
    out = [
        "// Generated by contracts/scripts/tokens.py from contracts/tokens/tokens.json. Do not edit by hand.",
        "package app.ezpztac.designsystem",
        "",
        "/** The design tokens, as plain numbers so they can be tested on a JVM and read by Compose and by tests alike. */",
        "object Tokens {",
        "    /** Colours as 0xAARRGGBB, one palette per theme. */",
        "    object Colors {",
    ]
    for theme, palette in tokens["colors"].items():
        out.append(f"        object {upper_first(theme)} {{")
        for name, value in palette.items():
            out.append(f"            const val {name}: Long = 0xFF{value[1:].upper()}")
        out.append("        }")
    out += ["    }", "", "    /** In dp. */", "    object Spacing {"]
    out += [f"        const val {k}: Int = {v}" for k, v in tokens["spacing"].items()]
    out += ["    }", "", "    /** In dp. */", "    object Radius {"]
    out += [f"        const val {k}: Int = {v}" for k, v in tokens["radius"].items()]
    out += ["    }", "", "    /** In dp. The touch target is above the 48 dp platform minimum, for gloves and vibration. */", "    object Size {"]
    out += [f"        const val {k}: Int = {v}" for k, v in tokens["size"].items()]
    out += ["    }", "", "    /** Size and line height in sp; `mono` is a monospaced face, for grids and key numbers. */", "    object Type {"]
    out.append("        data class Style(val size: Int, val lineHeight: Int, val weight: Int, val mono: Boolean)")
    out.append("")
    for name, style in tokens["type"].items():
        mono = "true" if style["mono"] else "false"
        out.append(f"        val {name} = Style({style['size']}, {style['lineHeight']}, {style['weight']}, {mono})")
    out += ["    }", "}", ""]
    return "\n".join(out)


def swift(tokens):
    out = [
        "// Generated by contracts/scripts/tokens.py from contracts/tokens/tokens.json. Do not edit by hand.",
        "",
        "/// The design tokens, as plain numbers so they can be tested on a Mac and read by SwiftUI and by tests alike. The same names as",
        "/// Android's `Tokens` (core-designsystem): a dp there is a point here.",
        "public enum Tokens {",
        "    /// Colours as 0xAARRGGBB, one palette per theme: a value rather than Android's object per theme, so a screen picks one at",
        "    /// run time.",
        "    public enum Colors {",
        "        public struct Palette: Equatable, Sendable {",
    ]
    names = list(next(iter(tokens["colors"].values())))
    out += [f"            public let {name}: UInt32" for name in names]
    out.append("        }")
    for theme, palette in tokens["colors"].items():
        out += ["", f"        public static let {theme} = Palette("]
        out += [
            f"            {name}: 0xFF{value[1:].upper()}{',' if i < len(palette) - 1 else ''}"
            for i, (name, value) in enumerate(palette.items())
        ]
        out.append("        )")
    out += ["    }", "", "    /// In points.", "    public enum Spacing {"]
    out += [f"        public static let {k}: Int = {v}" for k, v in tokens["spacing"].items()]
    out += ["    }", "", "    /// In points.", "    public enum Radius {"]
    out += [f"        public static let {k}: Int = {v}" for k, v in tokens["radius"].items()]
    out += [
        "    }",
        "",
        "    /// In points. The touch target is above the 44 pt platform minimum, for gloves and vibration.",
        "    public enum Size {",
    ]
    out += [f"        public static let {k}: Int = {v}" for k, v in tokens["size"].items()]
    out += [
        "    }",
        "",
        "    /// Size and line height in points; `mono` is a monospaced face, for grids and key numbers.",
        "    public enum `Type` {",
        "        public struct Style: Equatable, Sendable {",
        "            public let size: Int",
        "            public let lineHeight: Int",
        "            public let weight: Int",
        "            public let mono: Bool",
        "        }",
        "",
    ]
    for name, style in tokens["type"].items():
        mono = "true" if style["mono"] else "false"
        out.append(
            f"        public static let {name} = Style(size: {style['size']}, lineHeight: {style['lineHeight']}, "
            f"weight: {style['weight']}, mono: {mono})"
        )
    out += ["    }", "}", ""]
    return "\n".join(out)


def main(argv):
    mode = argv[1] if len(argv) > 1 else "check"
    tokens = load()
    outputs = [(ANDROID, kotlin(tokens)), (IOS, swift(tokens))]
    if mode == "write":
        for path, generated in outputs:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(generated)
            print(f"wrote {path.relative_to(ROOT)}")
        return 0
    if mode == "check":
        stale = [path for path, generated in outputs if not path.exists() or path.read_text() != generated]
        for path in stale:
            print(f"{path.relative_to(ROOT)} is out of date: run python contracts/scripts/tokens.py write")
        if stale:
            return 1
        print("tokens are current")
        return 0
    print("usage: tokens.py write|check")
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv))
